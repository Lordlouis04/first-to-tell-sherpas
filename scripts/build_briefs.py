def walk_strings(x):
    if isinstance(x, str):
        yield x
    elif isinstance(x, dict):
        for v in x.values():
            yield from walk_strings(v)
    elif isinstance(x, list):
        for v in x:
            yield from walk_strings(v)


def main():
    _, events = impact.load_prompt()
    drafts = {p.stem: json.loads(p.read_text(encoding="utf8")) for p in impact.CACHE_DIR.glob("*.json")}
    plan_raw = {f: json.loads((ROOT / "data" / "families" / f"{f}.json").read_text(encoding="utf8"))["plan"] for f in BRIEFS}
    OUT.mkdir(parents=True, exist_ok=True)
    bad_all = []
    for fid, b in BRIEFS.items():
        plan = plan_raw[fid]
        adv = plan["advisor"]
        src = json.dumps({"PLAN": impact.plan_digest(fid), "EVENTS": list(events.values())}, ensure_ascii=False)
        # reuse the grounding check from the impact engine on every text field
        probe = impact.ImpactResult.model_construct(draft=" ".join(walk_strings(b)), voice_script="", plan_figures_cited=[])
        bad = impact.ungrounded_figures(probe, src)
        if bad:
            bad_all.append((fid, bad))
        brief = {
            "family_id": fid,
            "advisor_name": f"{adv['name']} {adv['surname']}",
            "advisor_first": adv["name"],
            "firm_name": "Sherpas demo (synthetic)",
            "household": " & ".join(p["name"] for p in plan["household"].values() if p) + " " + plan["household"]["client"]["surname"],
            "target_minutes": 3,
            **b,
            # approved event messages for this family (event call variant): voice note + headline
            "events": {k: {"event_id": d["event_id"], "headline": events[d["event_id"]]["headline"], "type": events[d["event_id"]]["type"],
                           "subject": d["subject"], "audio": f"audio/{k}.mp3"}
                       for k, d in drafts.items() if d["family_id"] == fid},
        }
        (OUT / f"{fid}.json").write_text(json.dumps(brief, indent=1, ensure_ascii=False), encoding="utf8")
        print(f"{fid:8} facts={len(b['facts'])} topics={len(b['topics'])} events={len(brief['events'])}")
    if bad_all:
        sys.exit(f"UNGROUNDED figures: {bad_all}")


if __name__ == "__main__":
    main()
